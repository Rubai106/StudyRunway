export type TranslationKey = keyof typeof english;

export function translate(language: LanguageCode, key: TranslationKey): string {
  return translations[language]?.[key] ?? english[key];
}

export function getExamples(language: LanguageCode): string[] {
  return [
    translate(language, "example1"),
    translate(language, "example2"),
    translate(language, "example3"),
    translate(language, "example4"),
  ];
}

export function isLanguageCode(value: string | null): value is LanguageCode {
  return SUPPORTED_LANGUAGES.some((item) => item.code === value);
}

/** Added to each user request so the existing AI provider responds in the selected language. */
export function responseLanguageInstruction(language: LanguageCode): string {
  const names: Record<LanguageCode, string> = {
    en: "English",
    bn: "Bengali (বাংলা)",
    zh: "Simplified Chinese (简体中文)",
    hi: "Hindi (हिन्दी)",
    es: "Spanish (español)",
  };
  return `Respond in ${names[language]}. Use this language for the explanation, clarifying questions, and recommendations. Preserve user-provided names, currency codes, dates, and all numeric financial values exactly; do not change calculations or silently convert currencies. Keep the response concise and accurate.`;
}
